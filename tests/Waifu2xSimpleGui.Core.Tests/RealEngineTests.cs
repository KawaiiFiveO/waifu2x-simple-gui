using System.Collections.Concurrent;
using Waifu2xSimpleGui.Core.Engines;
using Waifu2xSimpleGui.Core.Jobs;
using Waifu2xSimpleGui.Core.Media;
using Waifu2xSimpleGui.Core.Settings;
using Waifu2xSimpleGui.Core.Tools;

namespace Waifu2xSimpleGui.Core.Tests;

/// <summary>Runs the real engines from the repo's engines/ folder; skipped when they aren't installed.</summary>
public sealed class RealEngineTests
{
    private static string? EnginesRoot()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "Waifu2xSimpleGui.slnx")))
            {
                return Path.Combine(dir.FullName, "engines");
            }
        }

        return null;
    }

    private static IUpscaler EngineOrSkip(UpscalerId id)
    {
        var engine = UpscalerCatalog.Create(id, EnginesRoot() ?? "missing");
        Assert.SkipUnless(engine.IsInstalled, $"{engine.ExecutablePath} not installed");
        return engine;
    }

    [Theory]
    [InlineData(UpscalerId.Waifu2x)]
    [InlineData(UpscalerId.RealEsrgan)]
    [InlineData(UpscalerId.RealCugan)]
    public async Task Probes_gpus(UpscalerId id)
    {
        var gpus = await EngineOrSkip(id).ProbeGpusAsync(TestContext.Current.CancellationToken);
        Assert.NotEmpty(gpus);
    }

    [Theory]
    [InlineData(UpscalerId.Waifu2x)]
    [InlineData(UpscalerId.RealEsrgan)]
    [InlineData(UpscalerId.RealCugan)]
    public async Task Upscales_a_batch_including_unicode_names_and_converted_formats(UpscalerId id)
    {
        EngineOrSkip(id);
        var ffmpeg = new ToolLocator(EnginesRoot()).FindFfmpeg();
        Assert.SkipWhen(ffmpeg is null, "ffmpeg not found");
        var ct = TestContext.Current.CancellationToken;
        var dir = Directory.CreateTempSubdirectory("w2xsg-real-");
        try
        {
            // 16x12 test images generated by ffmpeg: png (unicode name), jpg, tga (needs conversion), and a corrupt file.
            async Task<string> Make(string name)
            {
                var path = Path.Combine(dir.FullName, name);
                await Processes.ProcessRunner.RunAsync(ffmpeg!, ["-v", "error", "-y", "-f", "lavfi", "-i", "testsrc=size=16x12", "-frames:v", "1", path], cancellationToken: ct);
                return path;
            }

            var broken = Path.Combine(dir.FullName, "broken.png");
            await File.WriteAllTextAsync(broken, "not an image", ct);
            var files = new List<JobFile>
            {
                new(0, await Make("ünï cødé.png"), MediaKind.Image),
                new(1, await Make("b.jpg"), MediaKind.Image),
                new(2, await Make("c.tga"), MediaKind.Image),
                new(3, broken, MediaKind.Image),
            };

            var settings = new AppSettings
            {
                Engine = id,
                Scale = 2,
                NoiseLevel = -1,
                EnginesDirectory = EnginesRoot(),
                OutputDirectory = Path.Combine(dir.FullName, "out"),
                TempDirectory = Path.Combine(dir.FullName, "tmp"),
            };
            Assert.Null(JobRunner.Validate(settings));

            var final = new ConcurrentDictionary<int, FileUpdate>();
            await JobRunner.RunAsync(files, settings, new Sink(final), ct);

            Assert.All([0, 1, 2], i => Assert.Equal(FileState.Done, final[i].State));
            Assert.Equal(FileState.Failed, final[3].State);
            Assert.True(File.Exists(Path.Combine(settings.OutputDirectory, $"ünï cødé_{id.ToString().ToLowerInvariant()}_2x.png")));
            Assert.Empty(Directory.EnumerateDirectories(Path.Combine(settings.TempDirectory, SettingsStore.AppFolderName)));
        }
        finally
        {
            dir.Delete(recursive: true);
        }
    }

    private sealed class Sink(ConcurrentDictionary<int, FileUpdate> final) : IProgress<JobEvent>
    {
        public void Report(JobEvent value)
        {
            if (value is FileUpdate u)
            {
                final[u.FileId] = u;
            }
        }
    }
}
